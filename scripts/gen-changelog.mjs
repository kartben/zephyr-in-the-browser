/**
 * Generates src/changelog.ts from CHANGELOG.md at the repo root: CHANGELOG.md
 * is the single source of truth (edited by hand, also what GitHub renders),
 * and this script turns it into the plain data the help dialog changelog tab
 * reads. Run `node scripts/gen-changelog.mjs` after editing CHANGELOG.md.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const changelogPath = resolve(here, '../CHANGELOG.md')
const outPath = resolve(here, '../src/changelog.ts')

const HEADING_RE = /^##\s+(.+)$/
const VERSION_RE = /^\[([^\]]+)\]\s*-\s*(\d{4}-\d{2}-\d{2})$/
const ITEM_RE = /^-\s+(?:\*\*([^*:]+):?\*\*\s*)?(.+)$/

/**
 * @param {string} markdown
 * @returns {{ version: string, date: string | null, items: { tag: string, text: string }[] }[]}
 */
function parseChangelog(markdown) {
  const releases = []
  let current = null
  for (const line of markdown.split('\n')) {
    const heading = line.match(HEADING_RE)
    if (heading) {
      const versioned = heading[1].match(VERSION_RE)
      current = versioned
        ? { version: versioned[1], date: versioned[2], items: [] }
        : { version: heading[1].trim(), date: null, items: [] }
      releases.push(current)
      continue
    }
    const item = current && line.match(ITEM_RE)
    if (item) current.items.push({ tag: item[1] || '', text: item[2] })
  }
  return releases
}

// Drop sections with no items (e.g. a freshly reopened "## Unreleased" between
// releases) so the changelog tab never shows an empty heading.
const releases = parseChangelog(readFileSync(changelogPath, 'utf8')).filter(
  (release) => release.items.length > 0,
)
if (!releases.length) throw new Error(`No releases parsed from ${changelogPath}`)

const out = `/**
 * GENERATED by scripts/gen-changelog.mjs from CHANGELOG.md. Do not edit by
 * hand — edit CHANGELOG.md and re-run the script.
 */

export interface ChangelogItem {
  tag: string
  text: string
}

export interface ChangelogRelease {
  version: string
  date: string | null
  items: ChangelogItem[]
}

export const CHANGELOG: ChangelogRelease[] = ${JSON.stringify(releases, null, 2)}
`

writeFileSync(outPath, out)
console.log(`Wrote ${releases.length} releases to ${outPath}`)
