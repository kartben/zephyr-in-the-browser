static const uint8_t blank[FONT_HEIGHT];

const uint8_t *font_glyph(char c)
{
	if (c >= 'a' && c <= 'z' && c != 'x') {
		c = (char)(c - 'a' + 'A');
	}

	for (size_t i = 0; i < sizeof(glyph_chars) - 1U; i++) {
		if (glyph_chars[i] == c) {
			return glyphs[i];
		}
	}

	return blank;
}
